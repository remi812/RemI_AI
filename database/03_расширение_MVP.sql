-- Расширение существующей схемы remi_project. Выполнить один раз в RemI_AI.
-- Все изменения и демонстрационные записи применяются одной транзакцией.
BEGIN;

-- Можно начать диагностику с дисциплины, темы или компетенции.
ALTER TABLE remi_project.diagnostic_sessions
    ALTER COLUMN target_competency_id DROP NOT NULL,
    ADD COLUMN target_discipline_id INTEGER REFERENCES remi_project.disciplines(discipline_id),
    ADD COLUMN target_topic_id INTEGER REFERENCES remi_project.topics(topic_id),
    ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'completed'
        CHECK (status IN ('in_progress', 'completed', 'stopped')),
    ADD COLUMN stop_reason TEXT,
    ADD CONSTRAINT session_one_target CHECK (num_nonnulls(target_discipline_id, target_topic_id, target_competency_id) = 1),
    ADD CONSTRAINT session_student_unique UNIQUE (session_id, student_id);

-- Снимок каждого задания позволяет сохранить историю даже после изменения текста.
ALTER TABLE remi_project.questions
    ADD COLUMN difficulty SMALLINT CHECK (difficulty BETWEEN 1 AND 5),
    ADD COLUMN source VARCHAR(20) NOT NULL DEFAULT 'manual' CHECK (source IN ('manual', 'ai', 'reserve')),
    ADD COLUMN generator_model TEXT,
    ADD COLUMN generator_version TEXT,
    ADD COLUMN evaluation_rules TEXT,
    ADD COLUMN numeric_tolerance NUMERIC CHECK (numeric_tolerance >= 0),
    ADD COLUMN created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

CREATE TABLE remi_project.question_versions (
    question_version_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id INTEGER NOT NULL REFERENCES remi_project.questions(question_id),
    version_number INTEGER NOT NULL CHECK (version_number > 0),
    competency_id INTEGER NOT NULL REFERENCES remi_project.competencies(competency_id),
    answer_type VARCHAR(20) NOT NULL CHECK (answer_type IN ('choice', 'numeric', 'short_text')),
    question_text TEXT NOT NULL,
    expected_answer TEXT NOT NULL,
    explanation TEXT,
    evaluation_rules TEXT,
    numeric_tolerance NUMERIC CHECK (numeric_tolerance >= 0),
    options_snapshot JSONB,
    generator_model TEXT,
    generator_version TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (question_id, version_number),
    UNIQUE (question_id, question_version_id)
);

INSERT INTO remi_project.question_versions (question_id, version_number, competency_id, answer_type, question_text, expected_answer, explanation, options_snapshot)
SELECT q.question_id, 1, q.competency_id, q.answer_type, q.question_text, q.expected_answer, q.explanation,
       (SELECT jsonb_agg(o.option_text ORDER BY o.option_id) FROM remi_project.question_options o WHERE o.question_id = q.question_id)
FROM remi_project.questions q;

ALTER TABLE remi_project.student_answers
    ADD COLUMN question_version_id INTEGER,
    ADD COLUMN grading_method VARCHAR(20) CHECK (grading_method IN ('automatic', 'expert', 'ungraded')),
    ADD COLUMN grading_details TEXT,
    ADD CONSTRAINT answer_version_matches_question FOREIGN KEY (question_id, question_version_id)
        REFERENCES remi_project.question_versions(question_id, question_version_id);
UPDATE remi_project.student_answers a
SET question_version_id = v.question_version_id, grading_method = 'ungraded'
FROM remi_project.question_versions v
WHERE v.question_id = a.question_id AND v.version_number = 1;

-- Оценка освоения и уверенность — отдельные показатели. NULL означает отсутствие оценки.
CREATE TABLE remi_project.mastery_estimates (
    estimate_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES remi_project.students(student_id),
    competency_id INTEGER NOT NULL REFERENCES remi_project.competencies(competency_id),
    session_id INTEGER,
    mastery_score NUMERIC(5,4) CHECK (mastery_score BETWEEN 0 AND 1),
    evidence_confidence NUMERIC(5,4) CHECK (evidence_confidence BETWEEN 0 AND 1),
    knowledge_status VARCHAR(20) NOT NULL CHECK (knowledge_status IN ('mastered', 'possible_gap', 'not_assessed', 'needs_review')),
    explanation TEXT,
    algorithm_version TEXT,
    estimated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (session_id, student_id) REFERENCES remi_project.diagnostic_sessions(session_id, student_id)
);

CREATE TABLE remi_project.estimate_evidence (
    estimate_id INTEGER NOT NULL REFERENCES remi_project.mastery_estimates(estimate_id),
    answer_id INTEGER NOT NULL REFERENCES remi_project.student_answers(answer_id),
    PRIMARY KEY (estimate_id, answer_id)
);

-- Преподаватели и журнал проверок; создание доступа реализуется приложением.
CREATE TABLE remi_project.moderators (
    moderator_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) UNIQUE
);

CREATE TABLE remi_project.question_reviews (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id INTEGER NOT NULL,
    question_version_id INTEGER NOT NULL,
    moderator_id INTEGER REFERENCES remi_project.moderators(moderator_id),
    reviewer_type VARCHAR(20) NOT NULL CHECK (reviewer_type IN ('automatic', 'expert')),
    decision VARCHAR(20) NOT NULL CHECK (decision IN ('approved', 'rejected', 'needs_review')),
    details TEXT,
    rules_version TEXT,
    reviewed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (question_id, question_version_id) REFERENCES remi_project.question_versions(question_id, question_version_id),
    CHECK (reviewer_type <> 'expert' OR moderator_id IS NOT NULL)
);

ALTER TABLE remi_project.learning_resources
    ADD COLUMN provider VARCHAR(200),
    ADD COLUMN language VARCHAR(40),
    ADD COLUMN difficulty VARCHAR(50),
    ADD COLUMN access_type VARCHAR(30),
    ADD COLUMN review_status VARCHAR(20) NOT NULL DEFAULT 'pending' CHECK (review_status IN ('pending', 'approved', 'rejected')),
    ADD COLUMN link_checked_at TIMESTAMP;

CREATE TABLE remi_project.resource_reviews (
    review_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    resource_id INTEGER NOT NULL REFERENCES remi_project.learning_resources(resource_id),
    moderator_id INTEGER NOT NULL REFERENCES remi_project.moderators(moderator_id),
    decision VARCHAR(20) NOT NULL CHECK (decision IN ('approved', 'rejected', 'needs_review')),
    details TEXT,
    reviewed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE remi_project.learning_routes (
    route_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES remi_project.students(student_id),
    session_id INTEGER,
    target_discipline_id INTEGER REFERENCES remi_project.disciplines(discipline_id),
    target_topic_id INTEGER REFERENCES remi_project.topics(topic_id),
    target_competency_id INTEGER REFERENCES remi_project.competencies(competency_id),
    status VARCHAR(20) NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'archived')),
    explanation TEXT,
    algorithm_version TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (num_nonnulls(target_discipline_id, target_topic_id, target_competency_id) = 1),
    FOREIGN KEY (session_id, student_id) REFERENCES remi_project.diagnostic_sessions(session_id, student_id)
);

CREATE TABLE remi_project.route_steps (
    route_step_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    route_id INTEGER NOT NULL REFERENCES remi_project.learning_routes(route_id),
    position INTEGER NOT NULL CHECK (position > 0),
    competency_id INTEGER NOT NULL REFERENCES remi_project.competencies(competency_id),
    estimate_id INTEGER REFERENCES remi_project.mastery_estimates(estimate_id),
    status VARCHAR(20) NOT NULL DEFAULT 'planned' CHECK (status IN ('planned', 'in_progress', 'completed', 'skipped')),
    explanation TEXT,
    UNIQUE (route_id, position),
    UNIQUE (route_id, competency_id)
);

CREATE TABLE remi_project.route_step_resources (
    route_step_id INTEGER NOT NULL REFERENCES remi_project.route_steps(route_step_id),
    resource_id INTEGER NOT NULL REFERENCES remi_project.learning_resources(resource_id),
    reason TEXT,
    PRIMARY KEY (route_step_id, resource_id)
);

-- Запрет замкнутых цепочек предпосылок при добавлении и изменении связей.
CREATE FUNCTION remi_project.prevent_prerequisite_cycle() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    PERFORM pg_advisory_xact_lock(73642, 1);
    IF EXISTS (
        WITH RECURSIVE ancestors(id) AS (
            SELECT NEW.prerequisite_id
            UNION
            SELECT p.prerequisite_id FROM remi_project.prerequisites p
            JOIN ancestors a ON p.competency_id = a.id
            WHERE TG_OP <> 'UPDATE' OR (p.competency_id, p.prerequisite_id) <> (OLD.competency_id, OLD.prerequisite_id)
        ) SELECT 1 FROM ancestors WHERE id = NEW.competency_id
    ) THEN
        RAISE EXCEPTION 'Цикл в графе предварительных компетенций';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER prerequisite_no_cycle BEFORE INSERT OR UPDATE ON remi_project.prerequisites
FOR EACH ROW EXECUTE FUNCTION remi_project.prevent_prerequisite_cycle();

