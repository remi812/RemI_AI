BEGIN;

CREATE SCHEMA remi_project;

CREATE TABLE remi_project.students (
    student_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE remi_project.disciplines (
    discipline_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL UNIQUE,
    description TEXT,
    detail_level VARCHAR(20) NOT NULL CHECK (detail_level IN ('detailed', 'overview'))
);

CREATE TABLE remi_project.topics (
    topic_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discipline_id INTEGER NOT NULL REFERENCES remi_project.disciplines(discipline_id),
    name VARCHAR(150) NOT NULL,
    UNIQUE (discipline_id, name)
);

CREATE TABLE remi_project.competencies (
    competency_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id INTEGER NOT NULL REFERENCES remi_project.topics(topic_id),
    name VARCHAR(200) NOT NULL,
    description TEXT,
    UNIQUE (topic_id, name)
);

-- Каждая строка означает: prerequisite_id необходима для competency_id.
CREATE TABLE remi_project.prerequisites (
    competency_id INTEGER NOT NULL REFERENCES remi_project.competencies(competency_id),
    prerequisite_id INTEGER NOT NULL REFERENCES remi_project.competencies(competency_id),
    PRIMARY KEY (competency_id, prerequisite_id),
    CHECK (competency_id <> prerequisite_id)
);

CREATE TABLE remi_project.questions (
    question_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competency_id INTEGER NOT NULL REFERENCES remi_project.competencies(competency_id),
    question_text TEXT NOT NULL,
    answer_type VARCHAR(20) NOT NULL CHECK (answer_type IN ('choice', 'numeric', 'short_text')),
    expected_answer TEXT NOT NULL,
    explanation TEXT,
    validation_status VARCHAR(20) NOT NULL CHECK (validation_status IN ('pending', 'approved', 'rejected'))
);

CREATE TABLE remi_project.question_options (
    option_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id INTEGER NOT NULL REFERENCES remi_project.questions(question_id),
    option_text TEXT NOT NULL,
    UNIQUE (question_id, option_text)
);

CREATE TABLE remi_project.diagnostic_sessions (
    session_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES remi_project.students(student_id),
    target_competency_id INTEGER NOT NULL REFERENCES remi_project.competencies(competency_id),
    started_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finished_at TIMESTAMP,
    CHECK (finished_at IS NULL OR finished_at >= started_at)
);

CREATE TABLE remi_project.student_answers (
    answer_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES remi_project.diagnostic_sessions(session_id),
    question_id INTEGER NOT NULL REFERENCES remi_project.questions(question_id),
    answer_text TEXT NOT NULL,
    is_correct BOOLEAN,
    answered_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE remi_project.learning_resources (
    resource_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    resource_type VARCHAR(50) NOT NULL,
    url TEXT,
    description TEXT
);

CREATE TABLE remi_project.competency_resources (
    competency_id INTEGER NOT NULL REFERENCES remi_project.competencies(competency_id),
    resource_id INTEGER NOT NULL REFERENCES remi_project.learning_resources(resource_id),
    PRIMARY KEY (competency_id, resource_id)
);

