def public_questions(names, bank=QUESTIONS):
    """Верные ответы остаются на сервере; отсутствующие навыки не подменяются."""
    return [
        {"id": f"{name}:{index}", "competency": name, "text": text, "options": options}
        for name in names for index, (text, options, _) in enumerate(bank.get(name, []))
    ]


def evaluate(names, responses, bank=QUESTIONS):
    """По двум примерам показываем предварительный результат, не подтверждённый пробел."""
    expected = {f"{name}:{i}": (name, answer)
                for name in names for i, (_, _, answer) in enumerate(bank.get(name, []))}
    if set(responses) != set(expected):
        raise ValueError("Нужно ответить на все вопросы пилота.")
    counts = Counter()
    feedback = {}
    for question_id, (name, correct) in expected.items():
        value = responses[question_id]
        options = bank[name][int(question_id.rsplit(":", 1)[1])][1]
        if type(value) is not int or not 0 <= value < len(options):
            raise ValueError("Получен некорректный ответ.")
        feedback[question_id] = value == correct
        counts[name] += feedback[question_id]
    results = {name: {"correct": counts[name], "total": len(bank.get(name, [])),
                   "status": ("preliminary_correct" if counts[name] == len(bank[name]) else "needs_review")
                   if bank.get(name) else "not_assessed"}
            for name in names}
    return {"results": results, "feedback": feedback}
